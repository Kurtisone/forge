def _nothing_collected_node(state: AgentState) -> AgentState:
    """
    Report an empty collection, deterministically.

    The command ran, returned nothing, and there is no judgement to
    make: a diagnosis of zero lines is invention with extra steps.
    Until now this reached the synthesis with an empty block under a
    "--- collected logs ---" header, which is the same shape as
    handing the model a 403 and asking what is wrong with the service.

    This is the ONLY part of "the logs do not answer the question"
    that needs no model, and measuring the rest is what established
    that it is the only part available. See the module docstring.

    An empty log file is not a quiet system, and the message says so:
    `podman logs` on a container that has never written a line and
    `journalctl -u` on a window with no entries look identical from
    here, and neither is evidence that nothing is wrong.
    """
    source = state.context["log_source"]
    target = state.context.get("target_hint")
    subject = f"« {target} »" if target else "le système"

    state.final_output = (
        f"{non_answer.NOTHING_COLLECTED_PREFIX}`{source}` n'a rien renvoyé "
        f"pour {subject}. Il n'y a donc rien à diagnostiquer ici — et une "
        "sortie vide ne dit pas que tout va bien : elle dit que ce journal "
        "est vide, ce qui arrive aussi quand la cible écrit ailleurs ou "
        "quand la fenêtre interrogée ne couvre pas l'incident."
    )
    state.final_tool = "sysadmin"
    log.event("sysadmin.done", chars=len(state.final_output), collected=0)
    return state


def _collect_failed_node(state: AgentState) -> AgentState:
    """
    Report a failed collection, deterministically.

    Deliberately says what could not be read and stops. Naming the
    command matters more than it looks: the failure that produced this
    node was a proxy policy refusal that podman renders as an
    unmarshalling error, and the single most useful thing anyone could
    have been told is which command to run by hand.
    """
    source = state.context["log_source"]
    error = state.context["collect_failed"]
    target = state.context.get("target_hint")

    subject = f"« {target} »" if target else "le système"
    state.final_output = (
        f"{non_answer.COLLECT_FAILED_PREFIX}Je n'ai pas pu lire les logs de "
        f"{subject} : "
        f"la commande `{source}` a échoué.\n"
        f"{error}\n"
        "Tant que cette commande ne rend pas de logs, il n'y a rien à "
        "diagnostiquer — et ce message parle de la collecte, pas de l'état "
        "de la cible."
    )
    state.final_tool = "sysadmin"
    log.event("sysadmin.done", chars=len(state.final_output), collect_failed=True)
    return state


def _target_missed_node(state: AgentState) -> AgentState:
    """
    Report an unresolvable target, deterministically.

    Written entirely in code. This node exists because a model was
    asked to diagnose a service using logs from a different subsystem
    and did it -- fluently. There is no prompt for that; the answer is
    to not ask.
    """
    target = state.context["target_missed"]
    units = state.context["units"]
    containers = state.context["containers"]

    lines = [
        (
            f"{non_answer.TARGET_MISSED_PREFIX}« {target} » ne correspond à "
            f"aucune unité "
            f"systemd ni à aucun conteneur parmi ce que la découverte a "
            f"remonté ({len(units)} unités, {len(containers)} conteneurs)."
        )
    ]

    # Discovery failing is the interesting case and the common one: an
    # empty list means the proxy or busctl is down, not that the
    # machine has no services. Naming that turns "I could not find your
    # service" into "here is what to restart".
    for label, err_key, count in (
        ("unités systemd", "discover_units_error", len(units)),
        ("conteneurs", "discover_containers_error", len(containers)),
    ):
        err = state.context.get(err_key)
        if err:
            lines.append(f"La découverte des {label} a échoué : {err}")
        elif count == 0:
            lines.append(
                f"Aucun élément dans la liste des {label} — c'est "
                f"probablement la découverte qui est en panne, pas la cible."
            )

    close = difflib.get_close_matches(target, units + containers, n=3, cutoff=0.6)
    if close:
        lines.append("Cibles proches : " + ", ".join(close))

    state.final_output = "\n".join(lines)
    state.final_tool = "sysadmin"
    log.event("sysadmin.done", chars=len(state.final_output), target_missed=target)
    return state


def _clean_diagnosis_response(raw: str, log_block: str = "") -> str:
    """Same reasoning as review._clean_review_response and
    research._clean_synthesis_response (see forge/text_cleaning.py):
    this prompt asks for plain text, so the shared conditional-unwrap
    cleaner is reused here too, specifically to avoid the duplication
    drift already hit once between review and research in v3.10."""
    cleaned = strip_think_blocks(raw)

    unwrapped = try_unwrap_router_json(cleaned, source="sysadmin")
    if unwrapped is not None:
        cleaned = unwrapped

    if any(marker in cleaned for marker in _PROMPT_LEAK_MARKERS):
        log.warning("sysadmin: model echoed prompt instructions instead of answering")
        return "[error] Le modèle n'a pas généré de réponse exploitable. Réessayez."

    if any(fragment in cleaned for fragment in _EXAMPLE_LEAK_FRAGMENTS):
        log.warning(
            "sysadmin: model copied the GOOD ANSWER example verbatim "
            "instead of diagnosing the actual logs"
        )
        return "[error] Le modèle a recopié un exemple au lieu de générer un vrai diagnostic. Réessayez."

    if not cleaned:
        return "[error] Le modèle n'a pas généré de réponse. Réessayez."

    # Same guard review gained after run #b669174a. Not observed here
    # yet, and wired anyway: this graph already carries
    # _EXAMPLE_LEAK_FRAGMENTS, which is the same failure against a
    # different source text, and review/research last drifted apart
    # precisely because one of them was fixed alone (v3.10).
    if log_block and looks_like_a_copy(cleaned, log_block):
        log.warning("sysadmin: model echoed the logs instead of diagnosing them")
        return (
            "[error] Le modèle a recopié les logs au lieu de les analyser. Réessayez."
        )

    if len(cleaned) > _MAX_SYNTHESIS_OUTPUT_CHARS:
        cleaned = cleaned[:_MAX_SYNTHESIS_OUTPUT_CHARS].rstrip() + "…"

    return cleaned


def _truncate_log_block(log_block: str, budget: int) -> str:
    """Hard character cap independent of line count -- SYSADMIN_MAX_LOG_LINES
    alone isn't a safe context guarantee (line length varies a lot
    between journalctl/podman output). Keeps the END of the block:
    _run_fixed already returns at most the tail N lines via -n/--tail,
    so the most recent -- most relevant -- events are at the end."""
    if len(log_block) <= budget:
        return log_block
    return "…[troncated, showing the most recent output]…\n" + log_block[-budget:]


def _synthesize_node(state: AgentState) -> AgentState:
    question = (
        state.context.get("question")
        or "Diagnostique le problème et propose une solution."
    )
    source = state.context["log_source"]
    log_block = _truncate_log_block(
        state.context["collected_logs"], SYSADMIN_LOG_CHARS_BUDGET
    )

    # Run #be385d16: asked "pourquoi forge-embedding plante ?" about a
    # container that was up, the model read a routine llama.cpp
    # n_batch notice and concluded the service was crashing on "une
    # assertion ou une erreur interne NON AFFICHÉE" -- inventing the
    # evidence it lacked. Ninth time a wording fix has lost here.
    #
    # So this is not a wording fix. Discovery lists containers with
    # `podman ps`, no -a, which means presence in that list IS proof
    # the container was running. That fact is free, already collected,
    # and was being thrown away. It goes in the prompt as a FACT rather
    # than an instruction, and in the answer as a footer that holds
    # whatever the model decides to say.
    target = state.context.get("target_hint")
    running = bool(target) and target in state.context.get("containers", [])
    running_fact = _RUNNING_FACT.format(target=target) if running else ""

    prompt = _SYNTHESIS_PROMPT.format(
        today_line=today_line(),
        question=question,
        source=source,
        log_block=log_block,
        running_fact=running_fact,
    )

    # Language named in LAST position, and only when forge.lang is
    # sure -- same treatment recall got in the v3.12 dettes batch, for
    # the same reason: this prompt body is English prose, and it pulls
    # a French answer toward English all on its own. Appended rather
    # than templated in, so "last" cannot drift as the template grows.
    language_line = lang.line_for(question)

    log.event("sysadmin.llm_call", source=source, prompt_chars=len(prompt))
    try:
        # No grammar, so _grammar_for() supplies the ROUTER's. That is
        # deliberate -- see the header of forge/prose_grammar.py.
        raw = call_llm(prompt + language_line)
        log.event("sysadmin.raw_output", raw=raw)
        answer = _clean_diagnosis_response(raw, log_block)
        # The deterministic half. Naming the language in the prompt is
        # still a wording fix, and wording fixes have lost seven times
        # on this codebase. The retry re-sends the same prompt with a
        # different final line, so the KV prefix survives and only the
        # tail is recomputed.
        answer = lang.enforce(
            question,
            answer,
            retry=lambda line: _clean_diagnosis_response(
                call_llm(prompt + line), log_block
            ),
            enabled=ENFORCE_ANSWER_LANGUAGE,
        )
    except ProviderError as e:
        state.ok = False
        state.error = str(e)
        state.final_output = f"[error] LLM unavailable: {e}"
        return state

    if running and not answer.startswith("[error]"):
        answer += _RUNNING_FOOTER.format(target=target)

    state.final_output = answer
    state.final_tool = "sysadmin"
    log.event("sysadmin.done", chars=len(state.final_output), target_running=running)
    return state


#: The output-shaping half of the Harnais prompt -- what SHAPE the
#: answer must take, as opposed to what it may treat as true.
#:
#: forge/kernel/context_builder.py deliberately does not carry this.
#: The evidence half belongs with the World Model; this half belongs
#: next to _clean_diagnosis_response, which is what checks the model
#: obeyed it, and next to _EXAMPLE_LEAK_FRAGMENTS, which catches the
#: GOOD ANSWER example being copied instead of used. Splitting them the
#: other way would put the rule in one module and its enforcement in
#: another.
#:
#: Kept character-for-character in step with _SYNTHESIS_PROMPT's tail
#: on purpose: the same placeholder names, so the same leak detector
#: covers both. What it does NOT repeat is the evidence framing --
#: "these logs were gathered before you read the question", "never
#: treat the absence of an error as evidence" -- because the Context
#: Builder emits its own reading rules and two sets would disagree
#: about what the markers mean.
_CONTEXT_SHAPING = """
Respond in plain text ONLY. Do NOT wrap your answer in JSON, and do
NOT return a {"tool":...,"content":...} object -- that format is
for a different system (a routing decision) and never applies here.

GOOD ANSWER (this is only an example of FORM AND TONE -- these exact
names, files and details are fictional placeholders, not real
observations; copying any of them into your own answer is always
wrong, no matter what the context above actually says): Le service
exemple-service.service échoue au démarrage car la configuration
référence un fichier introuvable (/etc/exemple/manquant.conf). Je te
propose de vérifier que ce fichier existe et, si besoin, de le
recréer avant de relancer le service.
NEVER DO THIS: {"tool":"chat","content":"..."}

Now write your own answer using ONLY what actually appears above --
the words "exemple-service" and "manquant.conf" must never appear in
your answer. Same plain format as GOOD ANSWER. Be concise.
"""


def _harnais_path(state: AgentState) -> bool:
    """
    Whether this run takes route A: the Harnais instead of a log block.

    Only when NO target was named. A question about a named unit or
    container keeps the path it has -- validated collection, and the
    three refusals written in code when that validation fails. That
    boundary is not caution, it is measured: bench/context_builder_ab.py
    asked this model "pourquoi forge-llm plante ?" against a context
    stating the container could not be observed, and got back "plante
    CAR le socket de Podman n'existe pas" -- the instrument's failure
    returned as the phenomenon's cause, stable over four runs. A named
    target reaches _target_missed_node long before any of that, and
    that is where it stays.
    """
    return SYSADMIN_USE_HARNAIS and not state.context.get("target_hint")


def _observe_node(state: AgentState) -> AgentState:
    """
    Ask every Harnais collector what it can see, and record it.

    This runs a second `podman ps` -- _discover_node has already run
    one. Left as it is rather than threaded through: the collectors own
    their observation by design (a collector that took someone else's
    list would inherit that list's failure modes silently), and the
    duplicate is one proxied call against a local socket. The day it
    matters, the fix is to drop discover from this path, not to share
    its output.
    """
    world = InMemoryWorldModel()
    observations = harnais.observe(harnais.default_collectors())
    for observation in observations:
        world.record_observation(observation)

    state.context["world"] = world
    failed = [o.collector for o in observations if o.failed]
    log.event(
        "sysadmin.observe",
        collectors=len(observations),
        failed=failed,
        facts=sum(len(o.facts) for o in observations),
    )
    return state


def _observed_nothing(state: AgentState) -> bool:
    """True when not one collector produced a single Fact."""
    world = state.context.get("world")
    if world is None:
        return False
    return not any(world.current_state(domain) for domain in MVP_DOMAINS)


def _nothing_observed_node(state: AgentState) -> AgentState:
    """
    Report a total observation failure, deterministically.

    Written in code because the alternative was measured and is worse.
    bench/context_builder_ab.py removed the failing command's error text
    from the context, on the theory that a cause cannot be built out of
    a string that is not there. The model reached for the next nearest
    facts instead and declared HEALTHY ones guilty -- "plante car la
    charge CPU est élevée (0.9 sur 1 minute)", stable over three runs.

    Asked why something is wrong, this model returns a cause whatever
    the context holds; removing a candidate yields the next candidate,
    never a refusal. So when there is nothing to reason from, it is not
    asked. The error text still reaches the reader -- it reaches them
    from here, which is the same split _collect_failed_node already
    makes, and the same reason it makes it.
    """
    world = state.context["world"]
    lines = [
        (
            f"{non_answer.NOTHING_OBSERVED_PREFIX}Je n'ai rien pu observer sur "
            "cette machine : aucune source n'a répondu, donc il n'y a aucun "
            "fait sur lequel appuyer un diagnostic. Ce message parle de "
            "l'observation, pas de l'état de la machine — elle va peut-être "
            "très bien."
        )
    ]
    for domain in MVP_DOMAINS:
        error = world.observation_error(domain)
        if error:
            lines.append(f"- {domain} : {error}")

    state.final_output = "\n".join(lines)
    state.final_tool = "sysadmin"
    log.event("sysadmin.done", chars=len(state.final_output), observed_nothing=True)
    return state


def _context_synthesize_node(state: AgentState) -> AgentState:
    """One diagnosis, from the Context Builder's text rather than a log block."""
    question = (
        state.context.get("question")
        or "Diagnostique le problème et propose une solution."
    )
    context = ContextBuilder(state.context["world"]).build_for(
        question, SYSADMIN_CONTEXT_BUDGET_TOKENS
    )
    state.context["harnais_context"] = context

    # "/no_think" stays at position 0, where it was measured to matter
    # -- see the note above _SYNTHESIS_PROMPT. The Context Builder does
    # not emit it precisely so this stays true wherever it is called.
    prompt = "/no_think\n" + context + "\n" + _CONTEXT_SHAPING
    language_line = lang.line_for(question)

    log.event("sysadmin.llm_call", source="harnais", prompt_chars=len(prompt))
    try:
        raw = call_llm(prompt + language_line)
        log.event("sysadmin.raw_output", raw=raw)
        answer = _clean_diagnosis_response(raw)
        answer = lang.enforce(
            question,
            answer,
            retry=lambda line: _clean_diagnosis_response(call_llm(prompt + line)),
            enabled=ENFORCE_ANSWER_LANGUAGE,
        )
    except ProviderError as e:
        state.ok = False
        state.error = str(e)
        state.final_output = f"[error] LLM unavailable: {e}"
        return state

    state.final_output = answer
    state.final_tool = "sysadmin"
    log.event("sysadmin.done", chars=len(state.final_output), source="harnais")
    return state


def build() -> Graph:
    g = Graph("sysadmin", max_steps=6)
    g.add_node("discover", _discover_node)
    g.add_node("collect", _collect_node)
    g.add_node("target_missed", _target_missed_node, answers=False)
    g.add_node("collect_failed", _collect_failed_node, answers=False)
    g.add_node("nothing_collected", _nothing_collected_node, answers=False)
    g.add_node("synthesize", _synthesize_node)
    g.add_node("observe", _observe_node)
    g.add_node("nothing_observed", _nothing_observed_node, answers=False)
    g.add_node("context_synthesize", _context_synthesize_node)

    # Route A, and only for a question that names no target -- see
    # _harnais_path. Declared BEFORE the edge to collect, because Graph
    # takes the first matching edge, and the one to collect is
    # unconditional.
    g.add_edge("discover", "observe", condition=_harnais_path)
    g.add_edge("discover", "collect")

    # Nothing observed at all is a refusal written in code, not a
    # thinner prompt -- see _nothing_observed_node for the measurement
    # that settled it.
    g.add_edge("observe", "nothing_observed", condition=_observed_nothing)
    g.add_edge("observe", "context_synthesize")
    # Order matters -- Graph takes the first matching edge.
    g.add_edge(
        "collect",
        "target_missed",
        condition=lambda s: bool(s.context.get("target_missed")),
    )
    g.add_edge(
        "collect",
        "collect_failed",
        condition=lambda s: bool(s.context.get("collect_failed")),
    )
    g.add_edge(
        "collect",
        "nothing_collected",
        condition=lambda s: not (s.context.get("collected_logs") or "").strip(),
    )
    g.add_edge("collect", "synthesize")

    return g


def _format_discovered_list(names: list[str], max_shown: int = 8) -> str:
    """Names, not just a count -- capped so a host with dozens of
    active units doesn't produce an unreadable wall of text in the
    UI's expanded step detail."""
    if not names:
        return "aucun"
    shown = ", ".join(names[:max_shown])
    if len(names) > max_shown:
        shown += f", … (+{len(names) - max_shown})"
    return shown


def _to_sub_steps(state: AgentState) -> list[dict]:
    """Turn this run's internal graph trace (already recorded node by
    node by graph.py's Node.execute) into small, human-readable steps
    for the UI -- see forge/subtrace.py's docstring for why this is a
    separate publish rather than a widened tool contract."""
    units = state.context.get("units", [])
    containers = state.context.get("containers", [])
    units_error = state.context.get("discover_units_error")
    containers_error = state.context.get("discover_containers_error")
    collected_logs = state.context.get("collected_logs", "")
    collect_error = collected_logs if collected_logs.startswith("[error]") else None
    world = state.context.get("world")
    any_domain_unobserved = world is not None and any(
        not world.current_state(d) for d in MVP_DOMAINS
    )

    def discover_detail() -> str:
        # "unités" and not "services": what ListUnits returns is every
        # unit type systemd knows, and the line under this label has
        # held mounts, timers and targets since the day it was written.
        # It also held four device nodes out of eight names, which is
        # fixed one commit earlier -- this is the half of that fault
        # the filter does not reach.
        units_part = (
            f"unités : erreur ({units_error})"
            if units_error
            else f"unités : {_format_discovered_list(units)}"
        )
        containers_part = (
            f"containers : erreur ({containers_error})"
            if containers_error
            else f"containers : {_format_discovered_list(containers)}"
        )
        return f"{units_part} | {containers_part}"

    def collect_detail() -> str:
        missed = state.context.get("target_missed")
        if missed:
            return f"cible « {missed} » introuvable, aucun log collecté"
        source = state.context.get("log_source", "?")
        if collect_error:
            return f"source : {source} | erreur : {collect_error}"
        return f"source : {source}"

    def observe_detail() -> str:
        world = state.context.get("world")
        if world is None:
            return "aucune observation"
        seen, missing = [], []
        for domain in MVP_DOMAINS:
            facts = world.current_state(domain)
            (seen if facts else missing).append(
                f"{domain} ({len(facts)})" if facts else domain
            )
        parts = [f"observé : {', '.join(seen)}" if seen else "observé : rien"]
        if missing:
            # Named, never omitted. A domain that silently vanishes from
            # this line reads as one that had nothing to report, which
            # is the distinction the whole Harnais exists to keep.
            parts.append(f"non observé : {', '.join(missing)}")
        return " | ".join(parts)

    details = {
        "discover": discover_detail,
        "collect": collect_detail,
        "observe": observe_detail,
        "nothing_observed": lambda: "aucune source n'a répondu",
        "context_synthesize": lambda: (
            f"diagnostic généré depuis {len(state.context.get('harnais_context', ''))} "
            f"caractères de contexte ({len(state.final_output or '')} caractères)"
        ),
        "collect_failed": lambda: (
            f"collecte échouée : {state.context.get('collect_failed', '')[:120]}"
        ),
        "target_missed": lambda: (
            f"« {state.context.get('target_missed')} » absent de la découverte"
        ),
        "synthesize": lambda: (
            f"diagnostic généré ({len(state.final_output or '')} caractères)"
        ),
    }
    steps = subtrace.from_state(state, details)
    # sysadmin is the one graph whose per-step `ok` is not simply
    # state.ok: discover and collect can fail partially while the run
    # as a whole still finishes. from_state deliberately does not know
    # that, so it is overridden here rather than made a parameter no
    # other graph would pass.
    for step, ts in zip(steps, state.trace, strict=True):
        step["ok"] = (
            False
            if ts.decision_tool == "discover" and (units_error or containers_error)
            else False
            if ts.decision_tool == "collect"
            and (collect_error or state.context.get("target_missed"))
            else False
            if ts.decision_tool == "observe" and any_domain_unobserved
            else ts.tool_ok
        )
    return steps


def run(target_hint: str | None, question: str | None) -> str:
    """Discover active units/containers, collect logs for target_hint
    (or fall back to kernel logs), and synthesize one diagnosis."""
    state = build().run(
        target_hint or "",
        initial_context={"target_hint": target_hint, "question": question},
    )
    subtrace.publish(_to_sub_steps(state))
    return state.final_output or ""

"""
Forge sysadmin graph: discover -> collect -> synthesize.

Same reasoning as graphs/research.py: a deterministic fixed sequence,
never a router-driven multi-step chain. The router makes exactly ONE
decision (call "sysadmin"), the graph itself decides what to run next
-- no mid-flow judgment call is ever handed back to the model.

Security model (read-only, always):
  - discover_node runs two fixed, parameter-free commands
    (a busctl ListUnits call, podman ps) -- nothing here can be
    influenced by user input, so there is no injection surface at
    this step.
  - collect_node only ever runs a command built from a fixed template
    (see _COLLECT_TEMPLATES) whose one variable slot (a unit or
    container name) must appear verbatim in the list discover_node
    just returned. A name that isn't in that list is refused before
    any subprocess is started -- this is the entire threat model:
    nothing reaches subprocess.run() that wasn't independently
    confirmed to already exist on the system, and no shell=True is
    ever used, so there is no string-interpolation-into-a-shell
    surface either.
  - No mutation command exists in this module, at all. Restarting or
    stopping anything is explicitly out of scope for v3.11 -- this
    graph only ever reads logs and proposes; see the module docstring
    in tools/sysadmin.py for the human-in-the-loop reasoning, the
    same one already applied to tools/git.py staying read-only.

Nodes:
  discover_node    -- lists active systemd units and podman containers
  collect_node      -- fetches logs for one validated target (or
                        kernel logs as a fallback when no target was
                        named or found)
  synthesize_node   -- single LLM call producing a diagnosis and a
                        proposed fix, never an executed action

`.device` units never reach any of it: discovery drops them, because
a unit generated by udev has no journal of its own and is not a target
anyone can name on purpose. It is also what the user was reading --
four of the eight names shown in eighteen real runs were device nodes,
under a sub-step that called them `services`.

Three nodes written entirely in code refuse instead, and each exists
because a model, handed evidence about something else, answered
fluently anyway: target_missed (the named target is in neither list),
collect_failed (the command errored), nothing_collected (the command
returned no lines).

THE FOURTH CASE IS THE ONE THAT IS STILL OPEN, and it has now been
measured rather than assumed. Logs are collected before anyone reads
the question -- that is what makes the question answerable -- so they
may simply not contain the answer. The prompt says so and asks the
model to say so plainly; when it complies the reply is prose, which
forge/non_answer.py cannot match and the run does not report, so the
exchange is stored as though it were a diagnosis.

The obvious fix is a verdict the code can read. bench/sysadmin_verdict.py
asked for one four ways, over eight fixtures whose answer is known, on
2026-09-12:

    arm       right  FALSE NO  FALSE YES
    plain         5         0          3
    negated       5         3          0
    cite          5         0          3
    reason        3         3          2

Read the two error columns, not the first one. `plain` ("do these logs
answer?") is wrong only in the YES direction; `negated` (the same
question inverted) is wrong only in the NO direction. Each arm answers
the SHAPE of the question it was asked and gets right exactly the
fixtures where that shape happens to be correct. `cite`, which had to
name the line that answers and could have said NONE, never chose NONE
where it had the option -- it took line 1 in six cases of seven. And
`plain` said YES about an EMPTY log block, which is what
nothing_collected now refuses without asking anyone.

So there is no verdict channel here at this model size, in any of the
four shapes, and one deterministic case was hiding inside the idea.

Edges:
  discover_node  -> collect_node     (always)
  collect_node   -> synthesize_node  (always -- a failed individual
                                       collection still gets surfaced
                                       to the model as "[error] ...",
                                       it isn't fatal to the run)

Usage (Python):
  from forge.graphs.sysadmin import run
  print(run(target_hint="searxng", question="pourquoi ça redémarre ?"))
"""

